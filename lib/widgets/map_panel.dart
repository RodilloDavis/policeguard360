  void _checkMapLoaded() {
    Future.delayed(const Duration(seconds: 8), () {
      if (!mounted) return;
      if (!_controller.isCompleted) {
        setState(() => _mapError = true);
      }
    });
  }

  void _updateMarkers() {
    final activeReports = widget.reports
        .where((r) => r.status != 'Resolved')
        .toList();

    final reportMarkers = activeReports
        .map(_buildMarker)
        .where((m) => m != null)
        .cast<Marker>()
        .toSet();

    final allMarkers = <Marker>{...reportMarkers};
    if (_officerPosition != null) {
      allMarkers.add(_buildOfficerMarker(_officerPosition!));
    }

    setState(() => _markers = allMarkers);
  }

  Future<void> _startOfficerLocationTracking() async {
    try {
      LocationPermission perm = await Geolocator.checkPermission();
      if (perm == LocationPermission.denied) {
        perm = await Geolocator.requestPermission();
        if (perm == LocationPermission.denied) {
          debugPrint(
            '⚠️ Location permission denied — officer marker not shown',
          );
          return;
        }
      }
      if (perm == LocationPermission.deniedForever) {
        debugPrint('⚠️ Location permission permanently denied');
        return;
      }

      final initial = await Geolocator.getCurrentPosition(
        desiredAccuracy: LocationAccuracy.high,
      ).timeout(const Duration(seconds: 10));
      _onOfficerPositionUpdate(initial);

      _locationSub =
          Geolocator.getPositionStream(
            locationSettings: const LocationSettings(
              accuracy: LocationAccuracy.high,
              distanceFilter: 10,
            ),
          ).listen(
            _onOfficerPositionUpdate,
            onError: (e) => debugPrint('⚠️ Officer location stream error: $e'),
          );
    } catch (e) {
      debugPrint('⚠️ Could not start officer tracking: $e');
    }
  }

  void _onOfficerPositionUpdate(Position pos) {
    setState(() {
      _officerPosition = LatLng(pos.latitude, pos.longitude);
    });
    _updateMarkers();
  }

