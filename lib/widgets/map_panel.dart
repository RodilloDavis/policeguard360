    super.didUpdateWidget(oldWidget);
    if (oldWidget.reports != widget.reports ||
        oldWidget.selectedReport != widget.selectedReport) {
      _updateMarkers();
    }
    if (widget.selectedReport != null &&
        widget.selectedReport?.reportId != oldWidget.selectedReport?.reportId) {
      _panToReport(widget.selectedReport!);
    }
