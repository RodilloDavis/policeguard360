  bool _isValidCoord(double? lat, double? lng) {
    if (lat == null || lng == null) return false;
    return lat >= 7.265 && lat <= 7.401 && lng >= 125.605 && lng <= 125.731;
  }

  Marker? _buildMarker(EmergencyReport report) {
    double? lat = report.latitude;
    double? lng = report.longitude;

    if (!_isValidCoord(lat, lng)) {
      lat = null;
      lng = null;
    }

    if (lat == null || lng == null) {
      final barangayCoords = _findBarangayCoords(report.barangay);
      if (barangayCoords == null) return null;
      lat = barangayCoords.latitude;
      lng = barangayCoords.longitude;
    }

    final isSelected = widget.selectedReport?.reportId == report.reportId;
    final isCriticalSos = report.emergencyType.toLowerCase() == 'bubble';

    return Marker(
      markerId: MarkerId(report.reportId),
      position: LatLng(lat, lng),
      icon: BitmapDescriptor.defaultMarkerWithHue(_markerHue(report)),
      zIndex: isSelected ? 3.0 : (isCriticalSos ? 2.0 : 1.0),
      infoWindow: InfoWindow(
        title: '${report.typeIcon} ${report.displayType}',
        snippet: '📍 Brgy. ${report.barangay} · ${report.userName}',
      ),
      onTap: () => widget.onMarkerTap(report),
    );
  }

  LatLng? _findBarangayCoords(String barangay) {
    if (kPanaboBarangays.containsKey(barangay)) {
      return kPanaboBarangays[barangay];
    }
    final key = kPanaboBarangays.keys.firstWhere(
      (k) =>
          k.toLowerCase().contains(barangay.toLowerCase()) ||
          barangay.toLowerCase().contains(k.toLowerCase()),
      orElse: () => '',
    );
    if (key.isNotEmpty) return kPanaboBarangays[key];
    return null;
  }

  double _markerHue(EmergencyReport report) {
    if (report.status == 'Acknowledged') return BitmapDescriptor.hueBlue;
    switch (report.emergencyType.toLowerCase()) {
      case 'fire':
        return BitmapDescriptor.hueRed;
      case 'medical':
        return BitmapDescriptor.hueViolet;
      case 'flood':
        return BitmapDescriptor.hueCyan;
      case 'accident':
        return BitmapDescriptor.hueOrange;
      case 'crime':
        return BitmapDescriptor.hueAzure;
      case 'bubble':
        return BitmapDescriptor.hueRose;
      default:
        return BitmapDescriptor.hueYellow;
    }
  }

  Future<void> _panToReport(EmergencyReport report) async {
    double? lat = report.latitude;
    double? lng = report.longitude;

    if (!_isValidCoord(lat, lng)) {
      lat = null;
      lng = null;
    }

    if (lat == null || lng == null) {
      final coords = _findBarangayCoords(report.barangay);
      if (coords == null) return;
      lat = coords.latitude;
      lng = coords.longitude;
    }

    final ctrl = await _controller.future;
    await ctrl.animateCamera(
      CameraUpdate.newCameraPosition(
        CameraPosition(
          target: LatLng(lat, lng),
          zoom: 15.8,
          tilt: 20,
          bearing: 0,
        ),
      ),
    );
  }

  Future<void> _zoomIn() async {
    final ctrl = await _controller.future;
    ctrl.animateCamera(CameraUpdate.zoomIn());
  }

  Future<void> _zoomOut() async {
    final ctrl = await _controller.future;
    final zoom = await ctrl.getZoomLevel();
    if (zoom > 11.0) ctrl.animateCamera(CameraUpdate.zoomOut());
  }

  Future<void> _resetCamera() async {
    final ctrl = await _controller.future;
    ctrl.animateCamera(
      CameraUpdate.newCameraPosition(
        const CameraPosition(target: _kPanaboCityCenter, zoom: 13.5),
      ),
    );
  }

