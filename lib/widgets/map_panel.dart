// ─── MapPanel state ───────────────────────────────────────────────────────────
class _MapPanelState extends State<MapPanel> {
  final Completer<GoogleMapController> _controller = Completer();

  Set<Marker> _markers = {};
  bool _mapError = false;

  LatLng? _officerPosition;
  StreamSubscription<Position>? _locationSub;

  final Set<Polygon> _polygons = {};
  final Set<Polyline> _polylines = {};

  double _currentZoom = 13.5;
  double _lastRebuiltZoom = 0.0;
  Timer? _dashRebuildTimer;

  // Returns dash/gap sizes in meters for a given zoom level.
  ({double dash, double gap}) _dashSizeForZoom(double zoom) {
    const baseZoom = 13.0;
    const baseDash = 400.0;
    const baseGap = 200.0;
    final factor = Math.pow(2.0, baseZoom - zoom).toDouble();
    return (
      dash: (baseDash * factor).clamp(20.0, 2000.0),
      gap: (baseGap * factor).clamp(10.0, 1000.0),
    );
  }

  List<Polyline> _buildDashedPolylines(
    List<LatLng> points, {
    double dashMeters = 400,
    double gapMeters = 200,
    Color color = const Color(0xFFE53935),
    int width = 3,
    String idPrefix = 'dash',
  }) {
    final result = <Polyline>[];
    final closed = [...points, points.first];

    double accumulated = 0.0;
    bool drawing = true;
    var segmentPoints = <LatLng>[closed.first];
    int index = 0;

    for (int i = 0; i < closed.length - 1; i++) {
      final from = closed[i];
      final to = closed[i + 1];
      double segLen = _distanceMeters(from, to);
      double traveled = 0.0;

      while (traveled < segLen) {
        final budget = drawing ? dashMeters : gapMeters;
        final remaining = budget - accumulated;
        final available = segLen - traveled;

        if (available <= remaining) {
          accumulated += available;
          traveled = segLen;
          if (drawing) segmentPoints.add(to);
        } else {
          final fraction = (traveled + remaining) / segLen;
          final mid = LatLng(
            from.latitude + (to.latitude - from.latitude) * fraction,
            from.longitude + (to.longitude - from.longitude) * fraction,
          );
          traveled += remaining;
          accumulated = 0.0;

          if (drawing) {
            segmentPoints.add(mid);
            if (segmentPoints.length >= 2) {
              result.add(
                Polyline(
                  polylineId: PolylineId('${idPrefix}_$index'),
                  points: List.from(segmentPoints),
                  color: color,
                  width: width,
                ),
              );
              index++;
            }
            segmentPoints = [mid];
          } else {
            segmentPoints = [mid];
          }
          drawing = !drawing;
        }
      }
    }

    if (drawing && segmentPoints.length >= 2) {
      result.add(
        Polyline(
          polylineId: PolylineId('${idPrefix}_$index'),
          points: List.from(segmentPoints),
          color: color,
          width: width,
        ),
      );
    }

    return result;
  }

  double _distanceMeters(LatLng a, LatLng b) {
    const r = 6371000.0;
    final lat1 = a.latitude * 3.141592653589793 / 180;
    final lat2 = b.latitude * 3.141592653589793 / 180;
    final dLat = (b.latitude - a.latitude) * 3.141592653589793 / 180;
    final dLng = (b.longitude - a.longitude) * 3.141592653589793 / 180;
    final s =
        (Math.sin(dLat / 2) * Math.sin(dLat / 2)) +
        (Math.cos(lat1) *
            Math.cos(lat2) *
            Math.sin(dLng / 2) *
            Math.sin(dLng / 2));
    return r * 2 * Math.atan2(Math.sqrt(s), Math.sqrt(1 - s));
  }

  void _buildGadmPolygons() {
    final polygons = <Polygon>{};

    for (int i = 0; i < _kPanaboBarangayPolygons.length; i++) {
      final entry = _kPanaboBarangayPolygons[i];
      final name = entry['name'] as String;
      final points = entry['points'] as List<LatLng>;
      polygons.add(
        Polygon(
          polygonId: PolygonId('brgy_$i'),
          points: points,
          fillColor: Colors.transparent,
          strokeColor: Colors.transparent,
          strokeWidth: 0,
          consumeTapEvents: true,
          onTap: () => debugPrint('Barangay tapped: $name'),
        ),
      );
    }

    polygons.add(
      Polygon(
        polygonId: const PolygonId('panabo_city_boundary'),
        points: _kPanaboCityOuter,
        fillColor: Colors.transparent,
        strokeColor: Colors.transparent,
        strokeWidth: 0,
        zIndex: 1,
      ),
    );

    setState(() {
      _polygons.clear();
      _polygons.addAll(polygons);
    });

    _rebuildDashes(_currentZoom);
  }

  void _rebuildDashes(double zoom) {
    if ((zoom - _lastRebuiltZoom).abs() < 0.5 && _polylines.isNotEmpty) return;
    _lastRebuiltZoom = zoom;

    final sizes = _dashSizeForZoom(zoom);
    final dashedLines = _buildDashedPolylines(
      _kPanaboCityOuter,
      dashMeters: sizes.dash,
      gapMeters: sizes.gap,
      color: const Color(0x99E53935),
      width: 2,
      idPrefix: 'city_dash',
    );

    setState(() {
      _polylines.clear();
      _polylines.addAll(dashedLines);
    });
  }

